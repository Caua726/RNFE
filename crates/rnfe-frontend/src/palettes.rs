#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paletas_tem_64_cores_e_nomes() {
        for i in 0..COUNT {
            assert!(!name(i).is_empty());
            if let Some(p) = base(i) {
                assert_eq!(p.len(), 64);
                // a primeira cor é um cinza, a última linha termina em preto
                assert_eq!(p[63], [0, 0, 0]);
            }
        }
        assert!(base(0).is_none(), "0 é a paleta do núcleo");
    }
}
