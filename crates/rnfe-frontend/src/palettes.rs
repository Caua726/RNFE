//! Paletas alternativas de 64 cores.
//!
//! O 2C02 não tem paleta "certa": cada TV e cada captura dá uma cor diferente, e cada emulador
//! adota a sua. Aqui ficam as três mais usadas, para o jogador escolher: a do RNFE (a mesma de
//! sempre), uma mais saturada no estilo do FCEUX e uma mais fria/clara medida de composto.

/// Quantas paletas existem (0 = a padrão do núcleo).
pub const COUNT: usize = 3;

/// Nome curto para o menu.
pub fn name(index: usize) -> &'static str {
    match index {
        1 => "Viva",
        2 => "Composto",
        _ => "Padrão",
    }
}

/// As 64 cores da paleta `index`, ou `None` para a padrão do núcleo.
pub fn base(index: usize) -> Option<[[u8; 3]; 64]> {
    match index {
        1 => Some(unpack(&VIVA)),
        2 => Some(unpack(&COMPOSTO)),
        _ => None,
    }
}

fn unpack(rgb: &[u8; 192]) -> [[u8; 3]; 64] {
    let mut out = [[0u8; 3]; 64];
    for (i, c) in out.iter_mut().enumerate() {
        *c = [rgb[i * 3], rgb[i * 3 + 1], rgb[i * 3 + 2]];
    }
    out
}

